#!/usr/bin/env python3
"""Build book 09 from the unchanged two-part handoff, keeping every narration paragraph."""
import argparse,hashlib,json
from pathlib import Path
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
DOCS=ROOT/'docs/right-effort'
def compile_book():
 story=json.loads((DOCS/'storyboard.json').read_text());catalog=json.loads((DOCS/'scripture-catalog.json').read_text());quotes={q['id']:q for q in catalog}
 for f in json.loads((DOCS/'asset-manifest.json').read_text()):
  b=(DOCS/f['path']).read_bytes();assert len(b)==f['bytes'] and hashlib.sha256(b).hexdigest()==f['sha256'],f['path']
 assert len(story)==11 and len(catalog)==13 and sum(len(s['narration']) for s in story)==80
 scenes=[];pages=[]
 for source in story:
  image=source['asset'];dimensions=list(Image.open(DOCS/image).size) if image else None
  plan={'id':source['id'],'title':source['title'],'image':image,'alt':source['title'],'dimensions':dimensions,'start':len(pages),'artOverlay':source['artOverlay'],'darkOverlayOpacity':source.get('darkOverlayOpacity',0),'summaryRows':[]}
  scenes.append(plan)
  for n,text in enumerate(source['narration'],1):
   paired=[]
   for ref in source['scriptureRefs']:
    if n in ref['narrationParagraphs']:
     q=quotes[ref['quoteId']];paired.append({'quoteId':q['id'],'source':q['source'],'text':q['quote'],'relation':ref['relation']})
   pages.append({'scene':source['id'],'title':source['title'],'paragraphId':source['id']+'-P'+str(n).zfill(2),'paragraphNumber':n,'lines':[text],'quotes':paired,'image':'../../docs/right-effort/'+image,'dimensions':dimensions})
  if source.get('textCard'):
   # Original textCard remains intact in the handoff; apply the author's standing ending-word correction separately.
   lines=[x.replace('溫柔起點','起點') for x in source['textCard']]
   lines.insert(3,'本篇亦參照《相應部》四正勤相應；解讀仍請以原經文為準。')
   pages.append({'scene':source['id'],'title':source['title'],'lines':lines,'quotes':[],'image':None,'dimensions':None,'afterword':True})
 assert len(pages)==81 and pages[-1]['afterword']
 return '// Generated by scripts/build-right-effort.py; original handoff remains unchanged.\nconst BOOK = '+json.dumps({'title':'四正勤','layout':'caption-art-scripture','scenes':scenes,'pages':pages},ensure_ascii=False,indent=2)+';\n'
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args();target=ROOT/'right-effort/book/book-data.js';text=compile_book()
 if args.check:assert target.read_text()==text
 else:target.parent.mkdir(parents=True,exist_ok=True);target.write_text(text)
 print('33 file hashes; 11 scenes; 80 full narration paragraphs; 13 quotes; 81 pages: OK')
