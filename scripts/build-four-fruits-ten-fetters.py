#!/usr/bin/env python3
"""Build book 06 from the untouched author handoff and checked canon excerpts."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HANDOFF = ROOT / 'docs/four-fruits-ten-fetters'


def seconds(value):
    minute, second = map(int, value.split(':'))
    return minute * 60 + second


def compile_book():
    story = json.loads((HANDOFF / 'storyboard.json').read_text())
    manifest = json.loads((HANDOFF / 'assets-manifest.json').read_text())
    sources = json.loads((HANDOFF / 'verified-sources.json').read_text())
    art = {asset['sceneId']: asset for asset in manifest if asset['role'] == 'illustration'}
    assert len(art) == len(story['scenes']) == 11
    for asset in manifest:
        data = (HANDOFF / asset['path']).read_bytes()
        assert len(data) == asset['bytes']
        assert hashlib.sha256(data).hexdigest() == asset['sha256'], asset['path']
    scenes, pages = [], []
    last_at = -1
    for scene in story['scenes']:
        assert not scene['artOverlay'], 'Do not invent image-space overlays.'
        assert scene['topSubtitleLayout']['align'] == 'left'
        cues = scene['bottomScripture']['cues']
        cue_times = [seconds(cue['at']) for cue in cues]
        assert cue_times == sorted(set(cue_times))
        assert cue_times[0] == seconds(scene['start'])
        used_cues = set()
        scenes.append({
            'id': scene['id'], 'title': scene['title'], 'start': len(pages),
            'topSubtitleLayout': scene['topSubtitleLayout'], 'artOverlay': scene['artOverlay'],
        })
        for number, subtitle in enumerate(scene['topSubtitle'], 1):
            at = seconds(subtitle['at'])
            assert seconds(scene['start']) <= at < seconds(scene['end'])
            assert at > last_at
            last_at = at
            cue = next(cue for cue in reversed(cues) if seconds(cue['at']) <= at)
            used_cues.add(cue['at'])
            quote = sources['cues'][cue['source']]
            pages.append({
                'scene': scene['id'], 'subtitle': number, 'at': subtitle['at'],
                'title': scene['title'], 'lines': [subtitle['text']],
                'image': '../../docs/four-fruits-ten-fetters/' + scene['image'],
                'dimensions': [art[scene['id']]['width'], art[scene['id']]['height']],
                'verse': '\n\n'.join(quote['blocks']), 'verseLabel': quote['label'],
                'scriptureCue': cue['source'], 'scriptureCueAt': cue['at'],
                'source': '../#' + quote['canon'].replace('.', '-'),
            })
        assert used_cues == set(cue['at'] for cue in cues)
    assert len(pages) == 74
    by_time = {p['at']: p for p in pages}
    assert by_time['01:26']['scene'] == 'S03'
    assert '邠陀利花' in by_time['04:10']['lines'][0]
    assert by_time['05:00']['lines'] == ['永遠不再被欲界的粗重煩惱與情緒所激盪。']
    assert by_time['05:04']['lines'] == ['他們在此生結束後，將直接迎向清淨的高層天界，']
    scenes.append({'id': 'afterword', 'title': '製作說明｜溫柔的起點', 'start': len(pages),
                   'topSubtitleLayout': {'align': 'left', 'color': 'white'}, 'artOverlay': []})
    pages.append({'scene': 'afterword', 'subtitle': 1, 'at': None, 'title': '製作說明｜溫柔的起點',
                  'lines': [
                      '本繪本所呈現的內容，係以《增壹阿含經》卷二十〈聲聞品第二十八〉第七經為主，參照相關阿含經典與《相應部》所製作。',
                      '為了讓讀者更親近佛法，我們以圖文並茂的方式，用白話語言說明經意。',
                      '然而，繪本的詮釋難免簡略，無法完全涵蓋原經的深義。解讀仍請以原經文為準。',
                      '我們誠摯地鼓勵讀者參閱原經文，細細品味佛陀的智慧與慈悲。',
                      '也希望這本繪本能成為您走入經藏的溫柔起點。'],
                  'image': None, 'dimensions': None, 'verse': '', 'verseLabel': '', 'source': None,
                  'afterword': True})
    return '// Generated by scripts/build-four-fruits-ten-fetters.py; edit the source data instead.\nconst BOOK = ' + json.dumps({
        'title': story['title'], 'videoId': story['videoId'], 'scenes': scenes, 'pages': pages,
    }, ensure_ascii=False, indent=2) + ';\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'four-fruits-ten-fetters/book/book-data.js'
    compiled = compile_book()
    if args.check:
        assert target.read_text() == compiled, 'Reader data is stale.'
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(compiled)
    print('11 scenes / 74 captions + editorial afterword / 15 scripture cue states / 13 asset hashes: OK')
