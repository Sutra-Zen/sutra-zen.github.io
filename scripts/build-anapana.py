#!/usr/bin/env python3
"""Compile the intact Anapana handoff to the existing paragraph-page reader."""
import argparse,json,re,subprocess
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1];DOCS=ROOT/'docs/anapana'
def compile_book():
 subprocess.run(['python3',str(DOCS/'scripts/validate.py')],check=True)
 story=json.loads((DOCS/'storyboard.json').read_text());quotes=json.loads((DOCS/'scripture-catalog.json').read_text());overlays=json.loads((DOCS/'overlays.json').read_text())
 scenes=[];pages=[]
 for scene in story['scenes']:
  assert overlays[scene['sceneId']]==scene['overlays']
  plan={'id':scene['sceneId'],'title':scene['title'],'image':scene['image'],'alt':scene.get('bakedText',scene['title']),'dimensions':[scene['imageWidth'],scene['imageHeight']] if scene['image'] else None,'start':len(pages),'artOverlay':scene['overlays'],'sourceType':scene.get('sourceType'),'darkOverlayOpacity':0,'summaryRows':[]}
  scenes.append(plan)
  for n in scene['narration']:
   pages.append({'scene':scene['sceneId'],'title':scene['title'],'paragraphId':n['id'],'paragraphNumber':n['paragraph'],'lines':[n['text']],'quotes':[dict(quotes[q],quoteId=q,relation='影片下緣引文') for q in n['quoteIds']],'sourceNote':n['sourceNote'],'context':'論師實修補充' if scene['sceneId'] in ['S09','S10','S11'] else None,'image':'../assets/'+scene['sceneId']+'.webp','dimensions':plan['dimensions']})
  if scene['type']=='textSummary':
   sections=[]
   chunks=re.findall(r'<b>(.*?)</b>\s*(.*?)(?=\n\n<b>|\Z)',scene['summaryMarkdown'],re.S)
   assert len(chunks)==5
   for title,body in chunks:
    rows=[]
    if title.startswith('五、'):
     rows=[line.strip('|').strip().split('|') for line in body.splitlines() if line.startswith('|')][2:]
     rows=[[x.strip() for x in row] for row in rows];assert len(rows)==4;paragraphs=[]
    else:paragraphs=[p.strip() for p in re.split(r'<br\s*/?>',body.strip()) if p.strip()]
    sections.append({'title':title,'paragraphs':paragraphs,'rows':rows})
   pages.append({'scene':scene['sceneId'],'title':scene['title'],'lines':[],'quotes':[],'sourceNote':None,'context':None,'image':None,'dimensions':None,'afterword':True,'textSummary':sections,'editorialNote':['本繪本以《雜阿含經》803經為主，參照出處所列經典；調身與調心另採論師補充，與阿含主體分開對讀。','口白是影片的白話詮釋，解讀仍請以原經文為準。也希望這本繪本能成為您走入經藏的起點。']})
 assert len(pages)==119 and len(scenes)==12
 return '// Generated by scripts/build-anapana.py; original handoff remains intact.\nconst BOOK = '+json.dumps({'title':'安那般那與止觀','layout':'caption-art-scripture','scenes':scenes,'pages':pages},ensure_ascii=False,indent=2)+';\n'
if __name__=='__main__':
 parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args();target=ROOT/'anapana/book/book-data.js';content=compile_book()
 if args.check:assert target.read_text()==content
 else:target.parent.mkdir(parents=True,exist_ok=True);target.write_text(content)
 print('12 scenes / 118 intact narration paragraphs / 41 quotes / 12 overlays / 119 reader pages')
