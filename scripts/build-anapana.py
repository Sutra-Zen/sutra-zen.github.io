#!/usr/bin/env python3
"""Compile the intact Anapana handoff to the existing paragraph-page reader."""
import argparse,json,re,subprocess
from pathlib import Path
from site_seo import apply_page_seo
from lxml import html
ROOT=Path(__file__).resolve().parents[1];DOCS=ROOT/'docs/anapana'
def commentary_quotes(sources):
 """Use the guide's verified/commented excerpts for the existing reader cues."""
 sources={s['id']:s for s in sources['commentarialSources']}
 a=sources['bhavanakrama'];b=sources['anban'];text=a['excerpts'][0]
 markers=['足者','眼者','身者','肩者','頭者','齒與唇者','舌者','息者']
 parts=re.split('(?='+'|'.join(markers)+')',text)
 assert len(parts)==9
 intro=parts[0];clauses={next(m for m in markers if p.startswith(m)):p for p in parts[1:]}
 assert set(clauses)==set(markers)
 texts=[intro+clauses['足者'],clauses['身者'],clauses['肩者'],clauses['頭者'],clauses['眼者'],clauses['齒與唇者']+clauses['舌者'],clauses['息者']]
 updates={f'Q{i:02}':{'source':a['readerSourceLabel'],'text':value,'relation':'原文對讀','verification':'CBETA_Guanglun_quotation'} for i,value in enumerate(texts,32)}
 for i,value in enumerate(b['excerpts'],39):
  updates[f'Q{i:02}']={'source':b['readerStopSourceLabel'] if i==41 else b['readerSourceLabel'],'text':value,'relation':'原文對讀','verification':'author_supplied_correction' if i==41 else 'thesis_quotation'}
 assert len(updates)==10
 return updates
def compile_guide(sources):
 """Keep the two guide cards and the reader on the same source records."""
 content=(ROOT/'anapana/index.html').read_text()
 for source in sources['commentarialSources']:
  pattern=r'<article class="source-entry" id="'+re.escape(source['id'])+r'">.*?</article>'
  match=re.search(pattern,content,re.S);assert match
  card=html.fromstring(match[0]);card.xpath('.//h3')[0].text=source['title']
  card.xpath('.//*[@class="source-meta"]')[0].text=source['guideMeta']
  paragraphs=card.xpath('.//blockquote/p');assert len(paragraphs)==len(source['excerpts'])
  for paragraph,text in zip(paragraphs,source['excerpts']):paragraph.text=text
  content=content[:match.start()]+html.tostring(card,encoding='unicode')+content[match.end():]
 return apply_page_seo(content, "anapana/index.html")
def compile_book():
 subprocess.run(['python3',str(DOCS/'scripts/validate.py')],check=True)
 story=json.loads((DOCS/'storyboard.json').read_text());quotes=json.loads((DOCS/'scripture-catalog.json').read_text());overlays=json.loads((DOCS/'overlays.json').read_text())
 updates=commentary_quotes(json.loads((DOCS/'verified-sources.json').read_text()))
 edits=json.loads((DOCS/'reader-edits.json').read_text())
 for qid,label in edits['sourceLabels'].items():updates.setdefault(qid,{})['source']=label
 scenes=[];pages=[]
 for scene in story['scenes']:
  assert overlays[scene['sceneId']]==scene['overlays']
  plan={'id':scene['sceneId'],'title':scene['title'],'image':scene['image'],'alt':scene.get('bakedText',scene['title']),'dimensions':[scene['imageWidth'],scene['imageHeight']] if scene['image'] else None,'start':len(pages),'artOverlay':scene['overlays'],'sourceType':scene.get('sourceType'),'darkOverlayOpacity':0,'summaryRows':[]}
  scenes.append(plan)
  for n in scene['narration']:
   pages.append({'scene':scene['sceneId'],'title':scene['title'],'paragraphId':n['id'],'paragraphNumber':n['paragraph'],'lines':[n['text']],'quotes':[dict(quotes[q],quoteId=q,relation='影片下緣引文') | updates.get(q,{}) for q in n['quoteIds']],'sourceNote':None if scene['sceneId']=='S09' else n['sourceNote'],'context':'論師實修補充' if scene['sceneId'] in ['S10','S11'] else None,'image':'../assets/'+scene['sceneId']+'.webp','dimensions':plan['dimensions']} | edits['paragraphs'].get(n['id'],{}))
  if scene['type']=='textSummary':
   sections=[]
   chunks=re.findall(r'<b>(.*?)</b>\s*(.*?)(?=\n\n<b>|\Z)',scene['summaryMarkdown'],re.S)
   assert len(chunks)==5
   for title,body in chunks:
    rows=[]
    if title.startswith('五、'):
     rows=[line.strip('|').strip().split('|') for line in body.splitlines() if line.startswith('|')][2:]
     rows=[[x.strip() for x in row] for row in rows];assert len(rows)==4;paragraphs=[]
    else:paragraphs=[p.strip() for p in re.split(r'<br\s*/?>',body.strip()) if p.strip()]
    sections.append({'title':title,'paragraphs':paragraphs,'rows':rows})
   pages.append({'scene':scene['sceneId'],'title':scene['title'],'lines':[],'quotes':[],'sourceNote':None,'context':None,'image':None,'dimensions':None,'afterword':True,'textSummary':sections,'editorialNote':['本繪本以《雜阿含經》803經為主，參照出處所列經典；調身與調心另採論師補充，與阿含主體分開對讀。','口白是影片的白話詮釋，解讀仍請以原經文為準。也希望這本繪本能成為您走入經藏的起點。']})
 assert len(pages)==119 and len(scenes)==12
 return '// Generated by scripts/build-anapana.py; original handoff remains intact.\nconst BOOK = '+json.dumps({'title':'安那般那與止觀','layout':'caption-art-scripture','scenes':scenes,'pages':pages},ensure_ascii=False,indent=2)+';\n'
if __name__=='__main__':
 parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args();target=ROOT/'anapana/book/book-data.js';content=compile_book();guide=compile_guide(json.loads((DOCS/'verified-sources.json').read_text()))
 if args.check:assert target.read_text()==content and (ROOT/'anapana/index.html').read_text()==guide
 else:target.parent.mkdir(parents=True,exist_ok=True);target.write_text(content);(ROOT/'anapana/index.html').write_text(guide)
 print('12 scenes / 118 intact narration paragraphs / 41 original quotes + SA803 quiet-place excerpt (10 commentary sources synchronized) / 12 overlays / 119 reader pages')
